-- Esquema Sprint 2 (HU07 - HU12) portable entre PostgreSQL (Supabase) y H2

CREATE TABLE solicitudes (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES clientes(id_usuario),
    id_profesional BIGINT NOT NULL REFERENCES profesionales(id_usuario),
    id_servicio BIGINT NOT NULL REFERENCES servicios(id_servicio),
    descripcion VARCHAR(1000) NOT NULL,
    estado_solicitud VARCHAR(30) NOT NULL,
    motivo_rechazo VARCHAR(500),
    es_urgente BOOLEAN NOT NULL DEFAULT FALSE,
    precio_estimado NUMERIC(12, 2) NOT NULL,
    precio_final NUMERIC(12, 2),
    precio_final_confirmado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_solicitud TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_finalizacion TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_solicitudes_estado CHECK (
        estado_solicitud IN (
            'PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'EN_CAMINO',
            'EN_PROGRESO', 'FINALIZADA', 'EN_DISPUTA', 'CANCELADA', 'PAGADA'
        )
    ),
    CONSTRAINT chk_solicitudes_precio_est CHECK (precio_estimado > 0),
    CONSTRAINT chk_solicitudes_precio_fin CHECK (precio_final IS NULL OR precio_final > 0)
);

CREATE TABLE solicitud_fotos (
    id_foto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitudes(id_solicitud) ON DELETE CASCADE,
    ruta_archivo VARCHAR(500) NOT NULL
);

CREATE TABLE chats (
    id_chat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL UNIQUE REFERENCES solicitudes(id_solicitud) ON DELETE CASCADE,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mensajes (
    id_mensaje BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chat BIGINT NOT NULL REFERENCES chats(id_chat) ON DELETE CASCADE,
    id_remitente BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    contenido VARCHAR(1000) NOT NULL,
    fecha_envio TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_mensaje VARCHAR(20) NOT NULL DEFAULT 'ENVIADO',
    CONSTRAINT chk_mensajes_estado CHECK (estado_mensaje IN ('ENVIADO', 'LEIDO'))
);

CREATE TABLE resenas (
    id_resena BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL UNIQUE REFERENCES solicitudes(id_solicitud) ON DELETE CASCADE,
    id_cliente BIGINT NOT NULL REFERENCES clientes(id_usuario),
    id_profesional BIGINT NOT NULL REFERENCES profesionales(id_usuario),
    estrellas INTEGER NOT NULL,
    comentario VARCHAR(600),
    fecha_resena TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_resenas_estrellas CHECK (estrellas >= 1 AND estrellas <= 5)
);

CREATE INDEX idx_solicitudes_cliente ON solicitudes (id_cliente, fecha_solicitud);
CREATE INDEX idx_solicitudes_profesional ON solicitudes (id_profesional, estado_solicitud);
CREATE INDEX idx_solicitudes_servicio ON solicitudes (id_servicio);
CREATE INDEX idx_solicitud_fotos_solicitud ON solicitud_fotos (id_solicitud);
CREATE INDEX idx_mensajes_chat_fecha ON mensajes (id_chat, fecha_envio);
CREATE INDEX idx_mensajes_remitente ON mensajes (id_remitente);
CREATE INDEX idx_resenas_profesional_fecha ON resenas (id_profesional, fecha_resena);
CREATE INDEX idx_resenas_cliente ON resenas (id_cliente);
