ALTER TABLE usuarios ADD COLUMN suspendido_hasta TIMESTAMP WITH TIME ZONE;
ALTER TABLE usuarios ADD COLUMN motivo_suspension VARCHAR(500);

CREATE TABLE metodos_pago (
    id_metodo_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL REFERENCES clientes(id_usuario) ON DELETE CASCADE,
    token VARCHAR(160) NOT NULL UNIQUE,
    tipo VARCHAR(30) NOT NULL,
    franquicia VARCHAR(30) NOT NULL,
    ultimos_digitos VARCHAR(4) NOT NULL,
    titular VARCHAR(120) NOT NULL,
    mes_vencimiento INTEGER NOT NULL,
    anio_vencimiento INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_metodos_pago_tipo CHECK (tipo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO')),
    CONSTRAINT chk_metodos_pago_franquicia CHECK (franquicia IN ('VISA', 'MASTERCARD', 'AMEX', 'OTRA')),
    CONSTRAINT chk_metodos_pago_mes CHECK (mes_vencimiento >= 1 AND mes_vencimiento <= 12),
    CONSTRAINT chk_metodos_pago_anio CHECK (anio_vencimiento >= 2020)
);

CREATE TABLE pagos (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitudes(id_solicitud),
    id_metodo_pago BIGINT NOT NULL REFERENCES metodos_pago(id_metodo_pago),
    monto_servicio NUMERIC(12, 2) NOT NULL,
    tasa_garantia NUMERIC(12, 2) NOT NULL,
    cantidad NUMERIC(12, 2) NOT NULL,
    referencia_idempotencia VARCHAR(120) NOT NULL UNIQUE,
    referencia_pasarela VARCHAR(120),
    estado_pago VARCHAR(20) NOT NULL,
    motivo_rechazo VARCHAR(500),
    fecha_pago TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_pagos_monto_servicio CHECK (monto_servicio > 0),
    CONSTRAINT chk_pagos_tasa_garantia CHECK (tasa_garantia >= 0),
    CONSTRAINT chk_pagos_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_pagos_estado CHECK (estado_pago IN ('RETENIDO', 'LIBERADO', 'RECHAZADO', 'REEMBOLSADO'))
);

CREATE TABLE reportes (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitudes(id_solicitud),
    id_reportante BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_reportado BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    motivo VARCHAR(40) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    es_prioritario BOOLEAN NOT NULL DEFAULT FALSE,
    estado_reporte VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    accion_tomada VARCHAR(30),
    justificacion_resolucion VARCHAR(1000),
    dias_suspension INTEGER,
    decision_pago VARCHAR(20),
    id_admin_resolutor BIGINT REFERENCES administradores(id_usuario),
    fecha_reporte TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_resolucion TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_reportes_motivo CHECK (
        motivo IN (
            'NO_SE_PRESENTO', 'MAL_COMPORTAMIENTO', 'COBRO_INDEBIDO', 'MALA_CALIDAD',
            'CANCELACION_INJUSTIFICADA', 'MALTRATO', 'NO_PAGO', 'INFORMACION_FALSA'
        )
    ),
    CONSTRAINT chk_reportes_estado CHECK (estado_reporte IN ('PENDIENTE', 'RESUELTO', 'DESCARTADO')),
    CONSTRAINT chk_reportes_accion CHECK (
        accion_tomada IS NULL OR accion_tomada IN ('ADVERTENCIA', 'SUSPENSION_TEMPORAL', 'DESACTIVACION', 'DESCARTAR')
    ),
    CONSTRAINT chk_reportes_decision_pago CHECK (
        decision_pago IS NULL OR decision_pago IN ('SIN_CAMBIO', 'REEMBOLSAR', 'LIBERAR')
    )
);

CREATE TABLE casos_soporte (
    id_caso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_caso VARCHAR(40) NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_solicitud BIGINT REFERENCES solicitudes(id_solicitud),
    asunto VARCHAR(160) NOT NULL,
    descripcion VARCHAR(1200) NOT NULL,
    estado_caso VARCHAR(20) NOT NULL DEFAULT 'ABIERTO',
    respuesta_admin VARCHAR(1200),
    id_admin_respondedor BIGINT REFERENCES administradores(id_usuario),
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_respuesta TIMESTAMP WITH TIME ZONE,
    CONSTRAINT chk_casos_soporte_estado CHECK (estado_caso IN ('ABIERTO', 'RESPONDIDO', 'CERRADO'))
);

CREATE INDEX idx_metodos_pago_cliente ON metodos_pago (id_cliente, activo);
CREATE INDEX idx_pagos_solicitud ON pagos (id_solicitud, estado_pago);
CREATE INDEX idx_pagos_metodo ON pagos (id_metodo_pago);
CREATE INDEX idx_reportes_cola ON reportes (estado_reporte, es_prioritario, fecha_reporte);
CREATE INDEX idx_reportes_solicitud ON reportes (id_solicitud, estado_reporte);
CREATE INDEX idx_reportes_reportado ON reportes (id_reportado);
CREATE INDEX idx_reportes_reportante ON reportes (id_reportante);
CREATE INDEX idx_casos_soporte_usuario ON casos_soporte (id_usuario, fecha_creacion);
CREATE INDEX idx_casos_soporte_estado ON casos_soporte (estado_caso, fecha_creacion);
CREATE INDEX idx_casos_soporte_solicitud ON casos_soporte (id_solicitud);
