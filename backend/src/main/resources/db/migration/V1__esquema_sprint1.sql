-- Esquema portable compatible con PostgreSQL (Supabase) y H2 en modo PostgreSQL

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    celular VARCHAR(20) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(30) NOT NULL,
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado_cuenta VARCHAR(30) NOT NULL,
    intentos_fallidos INTEGER NOT NULL DEFAULT 0,
    bloqueado_hasta TIMESTAMP WITH TIME ZONE,
    foto_perfil VARCHAR(500),
    CONSTRAINT chk_usuarios_rol CHECK (rol IN ('CLIENTE', 'PROFESIONAL', 'ADMINISTRADOR')),
    CONSTRAINT chk_usuarios_estado_cuenta CHECK (estado_cuenta IN ('ACTIVA', 'SUSPENDIDA', 'DESACTIVADA'))
);

CREATE TABLE clientes (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    ubicacion VARCHAR(255) NOT NULL,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION
);

CREATE TABLE administradores (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuarios(id_usuario) ON DELETE CASCADE
);

CREATE TABLE profesionales (
    id_usuario BIGINT PRIMARY KEY REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    ubicacion VARCHAR(255) NOT NULL,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION,
    documento_identidad VARCHAR(500) NOT NULL,
    estado_verificacion VARCHAR(40) NOT NULL,
    motivo_rechazo VARCHAR(500),
    fecha_verificacion TIMESTAMP WITH TIME ZONE,
    id_admin_verificador BIGINT REFERENCES administradores(id_usuario),
    disponible BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_profesionales_verificacion CHECK (
        estado_verificacion IN ('PENDIENTE_VERIFICACION', 'VERIFICADO', 'RECHAZADO')
    )
);

CREATE TABLE profesional_certificaciones (
    id_certificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesional BIGINT NOT NULL REFERENCES profesionales(id_usuario) ON DELETE CASCADE,
    ruta_archivo VARCHAR(500) NOT NULL
);

CREATE TABLE categorias_oficio (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE servicios (
    id_servicio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesional BIGINT NOT NULL REFERENCES profesionales(id_usuario) ON DELETE CASCADE,
    id_categoria BIGINT NOT NULL REFERENCES categorias_oficio(id_categoria),
    tarifa_base NUMERIC(12, 2),
    precio_min NUMERIC(12, 2),
    precio_max NUMERIC(12, 2),
    CONSTRAINT uk_servicios_prof_cat UNIQUE (id_profesional, id_categoria),
    CONSTRAINT chk_servicios_rango CHECK (
        precio_min IS NULL OR precio_max IS NULL OR precio_min < precio_max
    )
);

CREATE TABLE auditoria_administrativa (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_administrador BIGINT NOT NULL REFERENCES administradores(id_usuario),
    accion VARCHAR(80) NOT NULL,
    entidad_afectada VARCHAR(80) NOT NULL,
    id_entidad BIGINT NOT NULL,
    detalle VARCHAR(1000),
    fecha_accion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notificaciones (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    titulo VARCHAR(160) NOT NULL,
    mensaje VARCHAR(600) NOT NULL,
    tipo VARCHAR(60) NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tokens_revocados (
    jti VARCHAR(100) PRIMARY KEY,
    fecha_expiracion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_revocacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_profesionales_busqueda ON profesionales (estado_verificacion, disponible);
CREATE INDEX idx_profesionales_admin ON profesionales (id_admin_verificador);
CREATE INDEX idx_certificaciones_profesional ON profesional_certificaciones (id_profesional);
CREATE INDEX idx_servicios_profesional ON servicios (id_profesional);
CREATE INDEX idx_servicios_categoria ON servicios (id_categoria);
CREATE INDEX idx_auditoria_admin ON auditoria_administrativa (id_administrador);
CREATE INDEX idx_auditoria_fecha ON auditoria_administrativa (fecha_accion);
CREATE INDEX idx_notificaciones_usuario ON notificaciones (id_usuario, leida);
CREATE INDEX idx_tokens_revocados_exp ON tokens_revocados (fecha_expiracion);
